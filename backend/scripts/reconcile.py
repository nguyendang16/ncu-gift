def get(api: str, path: str):
    req = urllib.request.Request(api + path, headers={"Accept-Language": "zh-TW"})
    return json.loads(urllib.request.urlopen(req, timeout=120).read())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--api", default="http://localhost:8000")
    ap.add_argument("--dataset", type=int, required=True)
    ap.add_argument("--out", default="reconciliation_INTERNAL.md")
    a = ap.parse_args()
    lines = ["# Reconciliation with the published annual reports (internal working document)", "",
             "Generated by `backend/scripts/reconcile.py`. ✓ = identical to the report; otherwise the difference is shown (system − report).", ""]
    tot_ok = tot_n = 0

    def cmp(rows, name, rep, sys_val):
        nonlocal tot_ok, tot_n
        tot_n += 1
        ok = rep == sys_val
        tot_ok += ok
        d = "" if ok else f"{sys_val - rep:+,.0f}"
        rows.append(f"| {name} | {rep:,.0f} | {sys_val:,.0f} | {'✓' if ok else d} |")

    for year in sorted(REPORT, reverse=True):
        r = REPORT[year]
        o = get(a.api, f"/api/overview?dataset_id={a.dataset}&year={year}&exceptional_threshold=1000000000")
        k = o["kpis"]
        rows = ["| Figure | Report | System | Difference |", "|---|---:|---:|---:|"]
        cmp(rows, "Cash total (NT$)", r["cash_total"], k["total"])
        cmp(rows, "Cash records", r["cash_records"], k["records"] - k["in_kind_records"])
        if "band_counts" in r:
            for i, b in enumerate(o["bands"]):
                cmp(rows, f"Gift band {i + 1}: {b['label']} (records)", r["band_counts"][i], b["count"])
        meth = {m["label"]: m for m in o["methods"]}
        for lab, (amt, n) in r["methods"].items():
            m = meth.get(lab, {"amount": 0, "count": 0})
            cmp(rows, f"Method {lab} (NT$)", amt, m["amount"] or 0)
            if n is not None:
                cmp(rows, f"Method {lab} (records)", n, m["count"])
        if "classes" in r:
            cls = {c["label"]: c for c in o["donor_classes"]}
            for lab, (amt, n) in r["classes"].items():
                c = cls.get(lab, {"amount": 0, "count": 0})
                cmp(rows, f"Donor type {lab} (NT$)", amt, c["amount"] or 0)
                cmp(rows, f"Donor type {lab} (records)", n, c["count"])
        grp = {g["label"]: g["amount"] or 0 for g in o["purpose_groups"]}
        for lab, amt in r["groups"].items():
            cmp(rows, f"Purpose {lab} (NT$)", amt, grp.get(lab, 0))
        sub = {s["label"]: s["amount"] or 0 for s in o["purpose_subs"]}
        for lab, amt in r["subs"].items():
            cmp(rows, f"Designated: {lab} (NT$)", amt, sub.get(lab, 0))
        col = {c["label"]: c["amount"] or 0 for c in o["colleges"]}
        for lab, amt in r["colleges"].items():
            cmp(rows, f"College {lab} (NT$)", amt, col.get(lab, 0))
        unc = [g for g in o["purpose_groups"] if g["label"] == "未分類"]
        lines += [f"## {year}", ""] + rows + [""]
        if unc:
            lines += [f"Gifts the table could not classify (waiting in the review queue): NT${unc[0]['amount'] or 0:,.0f} in {unc[0]['count']} records.", ""]
    lines.insert(3, f"**{tot_ok} of {tot_n} figures identical.**")
    lines.insert(4, "")
    open(a.out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{tot_ok}/{tot_n} identical -> {a.out}")


if __name__ == "__main__":
    main()
